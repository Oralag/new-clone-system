/**
 * 从内置知识库搜索
 */
export function searchBuiltinKnowledge(query: string): KnowledgeEntry[] {
  const q = query.toLowerCase()
  return BUILTIN_KNOWLEDGE.filter(entry =>
    entry.keywords.some(kw => q.includes(kw)) ||
    q.includes(entry.category.toLowerCase()) ||
    entry.answer.toLowerCase().includes(q.slice(0, 10))
  )
}
